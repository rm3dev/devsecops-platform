#!/usr/bin/env bash
# =============================================================================
# render-app.sh — re-render applications/<svc>/base/manifests.yaml locally.
#
# This is the EXACT command the CI step `updateGitOps` runs (helm version
# pinned in the agent image — v3.22.1). Use it after chart/values changes to
# review the diff in an MR, or to re-render every app:
#   for d in applications/*/; do ./scripts/render-app.sh "$(basename "$d")"; done
#
# Requires: helm v3 on PATH (same minor as the platform agents).
# =============================================================================
set -euo pipefail

SVC="${1:?usage: render-app.sh <service>   (directory name under applications/)}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP_DIR="$REPO_ROOT/applications/$SVC"
CHART="$REPO_ROOT/helm-charts/microservice-standard"

[[ -d "$APP_DIR" ]]  || { echo "FAIL: no application '$SVC' under applications/" >&2; exit 1; }
[[ -f "$APP_DIR/values.yaml" ]] || { echo "FAIL: $SVC has no values.yaml" >&2; exit 1; }
command -v helm >/dev/null || { echo "FAIL: helm not on PATH" >&2; exit 1; }

OUT="$APP_DIR/base/manifests.yaml"
{
  echo "# RENDERED OUTPUT — generated by 'helm template ${SVC} helm-charts/microservice-standard'"
  echo "# Source of truth: helm-charts/microservice-standard + applications/${SVC}/values.yaml"
  echo "# Regenerate: ./scripts/render-app.sh ${SVC}   (CI: updateGitOps does this automatically)"
  helm template "$SVC" "$CHART" -f "$APP_DIR/values.yaml"
} > "$OUT"

echo "OK: $OUT re-rendered (helm $(helm version --template '{{ .Version }}'))"
