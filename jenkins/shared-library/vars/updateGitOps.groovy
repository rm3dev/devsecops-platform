import groovy.json.JsonOutput
import org.company.devsecops.PipelineLogger
import org.company.devsecops.PlatformConfig
import org.company.devsecops.GitOpsRepo

/**
 * updateGitOps — render & commit the service's GitOps state (Phase 8, D-26).
 *
 * Runs on agent-general (helm + kustomize + yq pinned there). Flow:
 *   1. clone platform/gitops-repository (askpass auth — token never on disk/URL)
 *   2. deploymentType=helm  → helm template <slug> helm-charts/microservice-standard
 *                              -f applications/<slug>/values.yaml
 *                              → applications/<slug>/base/manifests.yaml (committed
 *                              render — what ArgoCD applies is exactly what git shows)
 *      deploymentType=kustomize → base/manifests.yaml is team-managed; skip render
 *   3. pin the built image DIGEST into overlays/<env>/kustomization.yaml
 *      (kustomize images: transformer → final image ref is name@sha256:…)
 *   4. commit + push main (rebase-retry; "[skip ci]" keeps GitLab quiet)
 *
 * ArgoCD (automated sync per environment) reconciles within seconds;
 * deployApplication then waits for sync+health.
 *
 * params:
 *   service    svc map from detectProject (required)
 *   env        target environment (default: gitops.defaultEnvironment — dev)
 *   digest     explicit sha256:… (default: this build's IMAGE_DIGEST_<slug>)
 *   imageName  explicit image name (default: this build's IMAGE_REF_<slug> repo part)
 *
 * env outputs: GITOPS_APP_<slug> ("<slug>-<env>"), GITOPS_ENV_<slug>
 * artifact:    reports/gitops-update-<slug>.json (archived by the Report stage)
 */
def call(Map params = [:]) {
    def svc = params.service ?: error('updateGitOps: "service" map is required')
    def log = new PipelineLogger(this, svc.name as String)
    final String STAGE = 'GitOps'

    def cfg = PlatformConfig.load(this, [servicePath: (svc.path ?: '.') as String])
    String slug = GitOpsRepo.slugify(svc.name as String)
    String team = GitOpsRepo.teamFromJob(this)

    List envs = (cfg.get('environments', ['dev', 'qa', 'uat', 'prod'])) as List
    String targetEnv = (params.env ?: cfg.get('gitops.defaultEnvironment', 'dev')) as String
    if (!envs.contains(targetEnv)) {
        error("${STAGE}: environment '${targetEnv}' is not a platform environment ${envs}")
    }

    String digest = (params.digest ?: env["IMAGE_DIGEST_${slug}"]) as String
    if (!digest || digest == 'null') {
        error("${STAGE}: no image digest recorded for '${svc.name}' — imageBuild must run in this build (or pass digest: explicitly; see platform/gitops-promotion)")
    }
    if (!GitOpsRepo.isDigest(digest)) { error("${STAGE}: invalid digest '${digest}'") }

    String domain = env.PLATFORM_DOMAIN
    if (!domain) { error("${STAGE}: PLATFORM_DOMAIN is not set on this agent (compose environment)") }
    String imageName = (params.imageName ?:
            env["IMAGE_REF_${slug}"]?.replaceAll(/:[^:@\/]+$/, '') ?:
            "registry.${domain}/${team}/${slug}") as String

    String branch         = cfg.get('gitops.branch', 'main') as String
    String chartPath      = cfg.get('gitops.chartPath', 'helm-charts/microservice-standard') as String
    String deploymentType = (svc.deploymentType ?: 'helm') as String

    withCredentials([string(credentialsId: 'gitops-commit-token', variable: 'GITOPS_TOKEN')]) {
        if (env.GITOPS_TOKEN == 'SET_IN_PHASE_8' || !env.GITOPS_TOKEN?.trim()) {
            error("${STAGE}: gitops-commit-token is still the Phase-8 placeholder. On the host run: " +
                  "./gitlab/scripts/50-gitops-repository.sh && docker compose -f docker-compose.yml --profile core up -d jenkins")
        }

        GitOpsRepo.withClone(this, [url: GitOpsRepo.repoUrl(this, cfg), branch: branch]) { String dir ->
            String appPath = "${dir}/applications/${slug}"
            if (!fileExists("${appPath}/base/kustomization.yaml")) {
                error("${STAGE}: no GitOps app for '${slug}'. Onboard it in platform/gitops-repository: copy " +
                      "applications/orders-api/ → applications/${slug}/, set values.yaml image.repository to " +
                      "${imageName}, keep the four overlays — then rebuild. See documentation/gitops.md §Onboarding.")
            }
            String overlay = "${appPath}/overlays/${targetEnv}/kustomization.yaml"
            if (!fileExists(overlay)) {
                error("${STAGE}: applications/${slug}/overlays/${targetEnv}/ does not exist — cannot target '${targetEnv}'")
            }

            if (deploymentType == 'helm') {
                log.info(STAGE, "rendering ${chartPath} + applications/${slug}/values.yaml → base/manifests.yaml")
                sh """#!/usr/bin/env bash
set -euo pipefail
{
  echo '# RENDERED OUTPUT — generated by CI (updateGitOps) from:'
  echo '#   ${chartPath} + applications/${slug}/values.yaml'
  echo '# Manual re-render: scripts/render-app.sh ${slug} — never edit this file by hand.'
  helm template '${slug}' '${dir}/${chartPath}' -f '${appPath}/values.yaml'
} > '${appPath}/base/manifests.yaml'
"""
            } else if (deploymentType == 'kustomize') {
                if (!fileExists("${appPath}/base/manifests.yaml")) {
                    error("${STAGE}: deploymentType=kustomize but applications/${slug}/base/manifests.yaml is missing (team-managed base)")
                }
                log.info(STAGE, "deploymentType=kustomize — base is team-managed; skipping helm render (digest pin still applies)")
            } else {
                error("${STAGE}: unknown deploymentType '${deploymentType}' (supported: helm, kustomize)")
            }

            GitOpsRepo.pinDigest(this, overlay, imageName, digest)

            String shortDigest = digest.substring(7, 19)
            String sha = GitOpsRepo.commitAndPush(this, dir,
                    "chore(gitops): ${slug} → ${targetEnv} @ sha256:${shortDigest}… [skip ci]")
            if (sha) {
                log.info(STAGE, "pushed ${sha.take(8)} — applications/${slug}/overlays/${targetEnv} @ sha256:${shortDigest}…")
            } else {
                log.info(STAGE, "gitops state already current for ${slug}@${targetEnv} (no commit needed)")
            }

            env["GITOPS_APP_${slug}"] = "${slug}-${targetEnv}"
            env["GITOPS_ENV_${slug}"] = targetEnv
            writeFile file: "reports/gitops-update-${slug}.json", text: JsonOutput.prettyPrint(JsonOutput.toJson([
                    service    : svc.name,
                    team       : team,
                    environment: targetEnv,
                    image      : imageName,
                    digest     : digest,
                    argoApp    : "${slug}-${targetEnv}",
                    commit     : sha ?: 'no-change',
                    rendered   : deploymentType == 'helm',
            ])) + '\n'
        }
    }
    log.info(STAGE, "ArgoCD reconciles ${slug}-${targetEnv} (automated sync) — deployApplication waits for health next")
}
