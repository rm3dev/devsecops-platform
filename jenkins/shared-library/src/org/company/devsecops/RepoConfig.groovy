package org.company.devsecops

/**
 * RepoConfig — build-time dependency-repository configuration writers.
 *
 * Every dependency byte flows through Nexus (D-16: agents have NO direct
 * internet route). Rather than baking repository config into agent images,
 * each build writes fresh config into ${WORKSPACE}/.platform/ so credentials
 * come from the Jenkins 'nexus-deploy' credential at runtime.
 *
 * Secret handling per ecosystem:
 *   maven settings.xml → ${env.NEXUS_USER} interpolation (Maven expands env)   — no secret on disk
 *   gradle init script → System.getenv('NEXUS_USER')                          — no secret on disk
 *   nuget.config       → %NEXUS_USER% expansion (NuGet native)                — no secret on disk
 *   .npmrc             → npm has no env interpolation for _auth: base64 IS
 *                        written to disk (workspace-private, agent-local) —
 *                        callers MUST invoke cleanup(script) in a finally block.
 *   pip/poetry/twine   → index URL assembled in the SHELL ($NEXUS_USER:$NEXUS_PASS
 *                        expand inside the sh step; Jenkins masks the values in logs).
 */
class RepoConfig implements Serializable {

    private static final long serialVersionUID = 1L

    static String platformDir(script) {
        return "${script.env.WORKSPACE}/.platform"
    }

    /** Host part of the Nexus base URL (for npmrc scope lines / trusted-host). */
    static String hostOf(String nexusBase) {
        return nexusBase.replaceFirst('^https?://', '').replaceAll('[:/].*$', '')
    }

    // ------------------------------------------------------------- maven ----
    /** settings.xml: mirror everything through maven-public + deploy servers. */
    static String mavenSettings(script, String nexusBase, Map repos) {
        String pub  = repos.mavenPublic    ?: 'maven-public'
        String rel  = repos.mavenReleases  ?: 'maven-releases'
        String snap = repos.mavenSnapshots ?: 'maven-snapshots'
        String path = "${platformDir(script)}/maven-settings.xml"
        // NOTE: \${env.*} stays LITERAL in the file — Maven expands it at runtime.
        script.writeFile file: path, text: """<?xml version="1.0" encoding="UTF-8"?>
<settings xmlns="http://maven.apache.org/SETTINGS/1.0.0">
  <mirrors>
    <mirror>
      <id>nexus-public</id>
      <mirrorOf>*</mirrorOf>
      <name>Nexus maven-public group (D-16: only dependency upstream)</name>
      <url>${nexusBase}/repository/${pub}/</url>
    </mirror>
  </mirrors>
  <servers>
    <server><id>nexus-public</id>   <username>\${env.NEXUS_USER}</username><password>\${env.NEXUS_PASS}</password></server>
    <server><id>nexus-releases</id> <username>\${env.NEXUS_USER}</username><password>\${env.NEXUS_PASS}</password></server>
    <server><id>nexus-snapshots</id><username>\${env.NEXUS_USER}</username><password>\${env.NEXUS_PASS}</password></server>
  </servers>
</settings>
"""
        script.echo "RepoConfig: wrote Maven settings (${path}) — mirror ${pub}, deploy servers nexus-releases/nexus-snapshots (URLs: ${nexusBase}/repository/${rel}|${snap})"
        return path
    }

    // ------------------------------------------------------------ gradle ----
    /** Init script: pluginManagement + project repos + maven-publish target. */
    static String gradleInit(script, String nexusBase, Map repos) {
        String pub  = repos.mavenPublic    ?: 'maven-public'
        String rel  = repos.mavenReleases  ?: 'maven-releases'
        String snap = repos.mavenSnapshots ?: 'maven-snapshots'
        String path = "${platformDir(script)}/nexus-init.gradle"
        // Inner \$ stays literal — evaluated by Gradle, not by this GString.
        // NOTE: maven{} blocks are written inline on purpose: a helper closure
        // would resolve maven() against the script (owner) instead of the
        // RepositoryHandler delegate and fail with MissingMethodException.
        script.writeFile file: path, text: """// Generated by RepoConfig (devsecops-shared-library) — do not edit in repos.
def nexusUser = System.getenv('NEXUS_USER') ?: ''
def nexusPass = System.getenv('NEXUS_PASS') ?: ''

beforeSettings { settings ->
    settings.pluginManagement {
        repositories {
            maven {
                name = 'nexus-public'
                url = '${nexusBase}/repository/${pub}/'
                allowInsecureProtocol = true
                credentials { username = nexusUser; password = nexusPass }
            }
            gradlePluginPortal()
        }
    }
}

allprojects {
    buildscript {
        repositories {
            maven {
                name = 'nexus-public'
                url = '${nexusBase}/repository/${pub}/'
                allowInsecureProtocol = true
                credentials { username = nexusUser; password = nexusPass }
            }
        }
    }
    repositories {
        maven {
            name = 'nexus-public'
            url = '${nexusBase}/repository/${pub}/'
            allowInsecureProtocol = true
            credentials { username = nexusUser; password = nexusPass }
        }
    }

    plugins.withId('maven-publish') {
        publishing {
            repositories {
                maven {
                    name = 'nexus'
                    url = '${nexusBase}/repository/' +
                          (project.version.toString().endsWith('-SNAPSHOT') ? '${snap}' : '${rel}') + '/'
                    allowInsecureProtocol = true
                    credentials { username = nexusUser; password = nexusPass }
                }
            }
        }
    }
}
"""
        return path
    }

    // --------------------------------------------------------------- npm ----
    /** .npmrc — the ONLY writer that places a secret on disk; cleanup() required. */
    static String npmrc(script, String nexusBase, Map repos, String user, String pass) {
        String pub   = repos.npmPublic ?: 'npm-public'
        String host  = repos.npmHosted ?: 'npm-hosted'
        String hostNoScheme = hostOf(nexusBase)
        String auth = "${user}:${pass}".getBytes('UTF-8').encodeBase64().toString()
        String path = "${platformDir(script)}/npmrc"
        script.writeFile file: path, text: """registry=${nexusBase}/repository/${pub}/
//${hostNoScheme}/repository/${pub}/:_auth=${auth}
//${hostNoScheme}/repository/${host}/:_auth=${auth}
always-auth=true
fund=false
audit=false
"""
        return path
    }

    // ------------------------------------------------------------ nuget ----
    /** nuget.config with %ENV% credential expansion (no secret on disk). */
    static String nugetConfig(script, String nexusBase, Map repos) {
        String pub  = repos.nugetPublic ?: 'nuget-public'
        String host = repos.nugetHosted ?: 'nuget-hosted'
        String path = "${platformDir(script)}/nuget.config"
        script.writeFile file: path, text: """<?xml version="1.0" encoding="utf-8"?>
<configuration>
  <packageSources>
    <clear />
    <add key="nexus-public" value="${nexusBase}/repository/${pub}/index.json" protocolVersion="3" />
    <add key="nexus-hosted" value="${nexusBase}/repository/${host}/index.json" protocolVersion="3" />
  </packageSources>
  <packageSourceCredentials>
    <nexus-public>
      <add key="Username" value="%NEXUS_USER%" />
      <add key="ClearTextPassword" value="%NEXUS_PASS%" />
    </nexus-public>
    <nexus-hosted>
      <add key="Username" value="%NEXUS_USER%" />
      <add key="ClearTextPassword" value="%NEXUS_PASS%" />
    </nexus-hosted>
  </packageSourceCredentials>
</configuration>
"""
        return path
    }

    // ----------------------------------------------------------- python ----
    /** SHELL-form PyPI index URL — expand $NEXUS_USER/$NEXUS_PASS inside sh steps. */
    static String pythonIndexShell(String nexusBase, Map repos) {
        String pub = (repos.pypiPublic ?: 'pypi-public') as String
        String withCreds = nexusBase.replaceFirst('^(https?://)', '$1$NEXUS_USER:$NEXUS_PASS@')
        return "${withCreds}/repository/${pub}/simple"
    }

    // ---------------------------------------------------------- cleanup ----
    /** Remove ${WORKSPACE}/.platform — MANDATORY after any npmrc() usage. */
    static void cleanup(script) {
        script.sh script: "rm -rf '${platformDir(script)}'", returnStatus: true
    }
}
