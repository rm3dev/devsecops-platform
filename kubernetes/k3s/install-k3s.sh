#!/usr/bin/env bash
# =============================================================================
# install-k3s.sh — Option B (D-01): pinned K3s lab cluster on the platform host.
#
# Design decisions (architecture D-27):
#   * --disable traefik --disable servicelb: the platform's OWN Traefik (Docker
#     Compose) owns host :80/:443; K3s must not fight it for those ports.
#     ArgoCD is exposed as a NodePort (argocd/install-argocd.sh).
#   * /etc/rancher/k3s/registries.yaml: docker.io, quay.io and ghcr.io are
#     MIRRORED through registry.<PLATFORM_DOMAIN> (Nexus docker-group →
#     docker-proxy/quay-proxy/ghcr-proxy) — cluster image pulls honor D-16
#     (Nexus is the only upstream). TLS trust via the platform CA
#     (TLS_MODE=internal-ca). docker-group enforces basic auth, so the
#     registry credentials (jenkins-ci / NEXUS_DEPLOY_PASSWORD) are stored in
#     registries.yaml — node-root-only 0600; this authenticates EVERY pull
#     through the mirror (workload images need no imagePullSecrets).
#   * /etc/hosts entries for *.<PLATFORM_DOMAIN>: K3s CoreDNS reads the node's
#     /etc/hosts via the NodeHosts plugin, so pods resolve gitlab/registry/vault
#     without external DNS (lab mode).
#
# Idempotent: re-running updates hosts/registries/CA (restarting k3s only when
# registries.yaml actually changed) and skips the install if k3s is running.
# Requires: root (sudo), curl. Run BEFORE argocd/kyverno/eso installs.
# =============================================================================
set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)/scripts/lib/common.sh"
load_env
require_cmd curl jq

K3S_VERSION="${K3S_VERSION:-v1.36.5+k3s1}"          # pinned; bump deliberately
K3S_DIR=/etc/rancher/k3s
REGISTRIES_FILE="$K3S_DIR/registries.yaml"
REGISTRY_HOST="registry.${PLATFORM_DOMAIN}"

[[ $EUID -eq 0 ]] || die "run as root: sudo $0   (k3s installs system services)"

# --- node IP (pods + kubeconfig reach platform services through it) ----------
HOST_IP="${PLATFORM_HOST_IP:-}"
if [[ -z "$HOST_IP" ]]; then
  HOST_IP="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}')"
fi
[[ -n "$HOST_IP" ]] || die "could not detect host IP — set PLATFORM_HOST_IP in .env"
log_info "platform host IP: ${HOST_IP}"

# --- /etc/hosts entries (K3s CoreDNS NodeHosts propagates them to pods) ------
SVC_NAMES="gitlab registry vault jenkins sonar sonarqube nexus grafana prometheus alertmanager traefik argocd"
for svc in $SVC_NAMES; do
  entry="${svc}.${PLATFORM_DOMAIN}"
  if grep -qE "(^|[[:space:]])${entry}([[:space:]]|$)" /etc/hosts; then
    # keep the mapping fresh if the host IP changed
    sed -i -E "/(^|[[:space:]])${entry}([[:space:]]|$)/s/^[0-9.]+/${HOST_IP}/" /etc/hosts
  else
    echo "${HOST_IP} ${entry}" >> /etc/hosts
    log_info "/etc/hosts: added ${entry} → ${HOST_IP}"
  fi
done

# --- platform CA for containerd (TLS_MODE=internal-ca) ------------------------
mkdir -p "$K3S_DIR"
if [[ "${TLS_MODE:-internal-ca}" == "internal-ca" ]]; then
  CA_FILE="$ROOT_DIR/reverse-proxy/certificates/ca.crt"
  [[ -f "$CA_FILE" ]] || die "platform CA missing ($CA_FILE) — run scripts/bootstrap.sh first"
  cp "$CA_FILE" "$K3S_DIR/platform-ca.crt"
  chmod 0644 "$K3S_DIR/platform-ca.crt"
fi

# --- registries.yaml (Nexus-only upstream, D-16 extended to the cluster) -----
# docker-group has forceBasicAuth=true (Phase 5) — containerd needs registry
# credentials for ALL mirrored pulls. They come from secrets/nexus-jenkins.env
# (same jenkins-ci account the pipeline publishes with).
NEXUS_ENV="$ROOT_DIR/secrets/nexus-jenkins.env"
[[ -f "$NEXUS_ENV" ]] || die "missing $NEXUS_ENV — run scripts/bootstrap.sh first"
set -a; source "$NEXUS_ENV"; set +a
[[ "${NEXUS_DEPLOY_PASSWORD:-SET_IN_PHASE_5}" != "SET_IN_PHASE_5" ]] \
  || die "NEXUS_DEPLOY_PASSWORD is still the bootstrap placeholder — run nexus/scripts/20-users.sh (Phase 5) first"

TLS_BLOCK=""
if [[ -f "$K3S_DIR/platform-ca.crt" ]]; then
  TLS_BLOCK="      tls:
        ca_file: $K3S_DIR/platform-ca.crt"
fi
AUTH_BLOCK="      auth:
        username: ${NEXUS_DEPLOY_USER:-jenkins-ci}
        password: ${NEXUS_DEPLOY_PASSWORD}"
NEW_REGISTRIES="$(cat <<EOF
# Generated by kubernetes/k3s/install-k3s.sh — mirrors route every public
# registry through the platform Nexus (docker-group). Credentials below are
# the jenkins-ci Nexus account; this file is node-root-only (chmod 0600).
mirrors:
  docker.io:
    endpoint:
      - "https://${REGISTRY_HOST}"
  quay.io:
    endpoint:
      - "https://${REGISTRY_HOST}"
  ghcr.io:
    endpoint:
      - "https://${REGISTRY_HOST}"
configs:
  "${REGISTRY_HOST}":
${TLS_BLOCK}
${AUTH_BLOCK}
EOF
)"
RESTART_K3S=false
if [[ -f "$REGISTRIES_FILE" ]] && [[ "$NEW_REGISTRIES" == "$(cat "$REGISTRIES_FILE")" ]]; then
  log_ok "registries.yaml unchanged"
else
  echo "$NEW_REGISTRIES" > "$REGISTRIES_FILE"
  chmod 0600 "$REGISTRIES_FILE"
  log_info "registries.yaml written (mirrors + auth → https://${REGISTRY_HOST})"
  RESTART_K3S=true
fi

# --- install (pinned) ----------------------------------------------------------
if systemctl is-active --quiet k3s 2>/dev/null; then
  log_ok "k3s service already running ($(k3s --version 2>/dev/null | head -1 || true))"
  if [[ "$RESTART_K3S" == true ]]; then
    log_info "registries.yaml changed — restarting k3s to apply mirrors…"
    systemctl restart k3s
  fi
else
  log_info "installing K3s ${K3S_VERSION} (traefik+servicelb disabled, D-27)…"
  curl -sfL https://get.k3s.io | \
    INSTALL_K3S_VERSION="$K3S_VERSION" \
    INSTALL_K3S_EXEC="server --disable traefik --disable servicelb --write-kubeconfig-mode 644 --tls-san ${HOST_IP} --tls-san 127.0.0.1" \
    sh -
fi

# --- wait for the node ---------------------------------------------------------
export KUBECONFIG=/etc/rancher/k3s/k3s.yaml
log_info "waiting for node Ready…"
deadline=$(( $(date +%s) + 180 ))
until kubectl get nodes 2>/dev/null | grep -q " Ready"; do
  [[ $(date +%s) -lt $deadline ]] || die "node not Ready within 180s — journalctl -u k3s"
  sleep 5
done
log_ok "K3s ${K3S_VERSION} ready: $(kubectl get nodes --no-headers | awk '{print $1, $5}')"

# --- cluster DNS for the platform names (durable; k3s-safe) ---------------------
# The kube-system/coredns cm is MANAGED by the k3s addon controller: manual
# edits (incl. its NodeHosts key) get reconciled away within minutes — live
# proof: NodeHosts patched in, pods resolved, key wiped again, NXDOMAIN.
# The official escape hatch is the coredns-custom cm (mounted at
# /etc/coredns/custom, imported as *.override by the stock Corefile): a
# template plugin answering A for every platform hostname with the node IP
# (+ NODATA for AAAA so dual-stack resolvers don't wander upstream).
NAMES_RE="($(echo "$SVC_NAMES" | tr ' ' '|'))"
cat > /tmp/coredns-plat-local.override <<EOF
template IN A ${PLATFORM_DOMAIN} {
  match ^${NAMES_RE}\\.${PLATFORM_DOMAIN}\\.\$
  answer "{{ .Name }} 60 IN A ${HOST_IP}"
}
template IN AAAA ${PLATFORM_DOMAIN} {
  match ^${NAMES_RE}\\.${PLATFORM_DOMAIN}\\.\$
  rcode NOERROR
}
EOF
APPLY_OUT="$(kubectl -n kube-system create configmap coredns-custom \
  --from-file=plat-local.override=/tmp/coredns-plat-local.override \
  --dry-run=client -o yaml | kubectl apply -f -)"
rm -f /tmp/coredns-plat-local.override
if [[ "$APPLY_OUT" == *created* || "$APPLY_OUT" == *configured* ]]; then
  # fresh pods are required to mount the (previously absent) optional volume
  kubectl -n kube-system rollout restart deploy/coredns >/dev/null
  kubectl -n kube-system rollout status deploy/coredns --timeout=120s >/dev/null
fi
log_ok "coredns-custom template live — pods resolve *.${PLATFORM_DOMAIN} → ${HOST_IP}"

cat <<EOF

Next: kubernetes/scripts/00-bootstrap-cluster.sh   (ArgoCD → Kyverno → ESO → Vault)
Kubeconfig for your shell:  export KUBECONFIG=/etc/rancher/k3s/k3s.yaml
EOF
